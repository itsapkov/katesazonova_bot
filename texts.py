def access_granted(access_url: str) -> str:
    tail = (
        f"\n\n<a href=\"{access_url}\">Открыть Shopping List</a>"
        if access_url
        else "\n\nКатя пришлёт доступ в течение нескольких минут."
    )
    return (
        f"Оплата прошла. Спасибо! Добро пожаловать в <b>{PRODUCT_NAME}</b> 🤍\n\n"
        "Если потеряете это сообщение, ссылку всегда можно получить снова "
        "в меню — кнопка «Мой Shopping List»." + tail
    )


# Повторная выдача ссылки (requirement 8)
